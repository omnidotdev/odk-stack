//! TypeScript interface emitter.
//!
//! Generates TypeScript interfaces and type aliases from a compiled schema.

use anyhow::Result;
use camino::Utf8Path;
use odk_schema::{CompiledModel, CompiledSchema, CompiledType, CompiledUnion, ScalarType};
use std::fs::{self, File};
use std::io::Write;

/// Emit TypeScript interfaces and type aliases.
pub fn emit(schema: &CompiledSchema, out_dir: &Utf8Path) -> Result<()> {
    let ts_dir = out_dir.join("typescript");
    fs::create_dir_all(&ts_dir)?;

    let mut lines = Vec::new();
    lines.push("// Generated by ODK".to_string());
    lines.push(String::new());

    // Emit unions as type aliases
    for union in &schema.unions {
        if let Some(desc) = &union.description {
            lines.push(format!("/** {} */", desc));
        }
        lines.push(union_to_typescript(union));
        lines.push(String::new());
    }

    // Emit models as interfaces
    for model in &schema.models {
        if let Some(desc) = &model.description {
            lines.push(format!("/** {} */", desc));
        }
        lines.extend(model_to_typescript(model));
        lines.push(String::new());
    }

    let path = ts_dir.join("types.ts");
    let mut file = File::create(&path)?;
    file.write_all(lines.join("\n").as_bytes())?;

    Ok(())
}

fn union_to_typescript(union: &CompiledUnion) -> String {
    let variants: Vec<String> = union
        .variants
        .iter()
        .map(|v| format!("\"{}\"", v.name))
        .collect();
    format!("export type {} = {};", union.name, variants.join(" | "))
}

fn model_to_typescript(model: &CompiledModel) -> Vec<String> {
    let mut lines = Vec::new();
    lines.push(format!("export interface {} {{", model.name));

    for field in &model.fields {
        let optional = if field.optional == Some(true) {
            "?"
        } else {
            ""
        };
        let ts_type = compiled_type_to_typescript(&field.field_type);

        if let Some(desc) = &field.description {
            lines.push(format!("  /** {} */", desc));
        }
        lines.push(format!("  {}{}: {};", field.name, optional, ts_type));
    }

    lines.push("}".to_string());
    lines
}

fn compiled_type_to_typescript(compiled_type: &CompiledType) -> String {
    match compiled_type {
        CompiledType::Scalar { name } => scalar_to_typescript(name),
        CompiledType::Ref { name } => name.clone(),
        CompiledType::Array { items } => format!("{}[]", compiled_type_to_typescript(items)),
        CompiledType::Literal { value } => match value {
            odk_schema::LiteralValue::String(s) => format!("\"{}\"", s),
            odk_schema::LiteralValue::Number(n) => n.to_string(),
            odk_schema::LiteralValue::Bool(b) => b.to_string(),
        },
        CompiledType::Union { variants } => {
            let types: Vec<String> = variants.iter().map(compiled_type_to_typescript).collect();
            types.join(" | ")
        }
        CompiledType::Object { fields } => {
            let field_strs: Vec<String> = fields
                .iter()
                .map(|f| {
                    let optional = if f.optional == Some(true) { "?" } else { "" };
                    format!(
                        "{}{}: {}",
                        f.name,
                        optional,
                        compiled_type_to_typescript(&f.field_type)
                    )
                })
                .collect();
            format!("{{ {} }}", field_strs.join("; "))
        }
    }
}

fn scalar_to_typescript(scalar: &ScalarType) -> String {
    match scalar {
        ScalarType::String | ScalarType::Url => "string".to_string(),
        ScalarType::Int32 | ScalarType::Int64 | ScalarType::Float32 | ScalarType::Float64 => {
            "number".to_string()
        }
        ScalarType::Boolean => "boolean".to_string(),
        ScalarType::Date | ScalarType::PlainDate => "string".to_string(), // ISO date string
        ScalarType::Datetime | ScalarType::UtcDateTime | ScalarType::OffsetDateTime => {
            "Date".to_string()
        }
        ScalarType::PlainTime => "string".to_string(), // ISO time string
        ScalarType::Duration => "string".to_string(),  // ISO duration string
        ScalarType::Bytes => "Uint8Array".to_string(),
        ScalarType::Unknown => "unknown".to_string(),
    }
}
